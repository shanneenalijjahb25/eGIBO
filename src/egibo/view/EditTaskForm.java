    private void populateFields() {
        if (taskToEdit == null) return;

        // Populate common fields
        txtboxTitle.setText(taskToEdit.getTitle());
        jTextArea1.setText(taskToEdit.getDescription());
        
        if (taskToEdit.getDueDate() != null) {
            txtboxDate.setText(taskToEdit.getDueDate().toString());
        }
        
        int importanceValue = taskToEdit.getImportance(); 
        if (importanceValue >= 4) {
            comboImportance.setSelectedItem("4 — High (Important / Strict Deadline)");
        } else if (importanceValue == 3) {
            comboImportance.setSelectedItem("3 — Normal (Standard task)");
        } else if (importanceValue == 2) {
            comboImportance.setSelectedItem("2 — Minor (Nice to finish today)");
        } else {
            comboImportance.setSelectedItem("1 — Low Priority (Optional / Do when free)");
        }
        
        // Polymorphic Type Handling for Edit Form
        if (taskToEdit instanceof FixedTask) {
            FixedTask fixed = (FixedTask) taskToEdit;
            rbFixedTask.setSelected(true);
            cardLayout.show(pnlDynamicContainer, "pnlFixedTask"); // shows pnlFixedTask
            
            if (fixed.getStartTime() != null) {
                txtboxStartTime.setText(fixed.getStartTime().toString());
            }
            if (fixed.getEndTime() != null) {
                txtboxEndTime.setText(fixed.getEndTime().toString());
            }
            
        } else if (taskToEdit instanceof FlexibleTask) {
            FlexibleTask flexible = (FlexibleTask) taskToEdit;
            rbFlexibleTask.setSelected(true);
            cardLayout.show(pnlDynamicContainer, "pnlFlexibleTask"); // shows pnlFlexibleTask
            
            txtboxHours.setText(String.valueOf(flexible.getHours()));
            if (flexible.getWorkStartTime() != null) {
                txtboxFlexTime.setText(flexible.getWorkStartTime().toString());
            }
        }
    }
